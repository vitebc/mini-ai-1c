/// Правила изоляции изменений с шаблонами маркеров пользователя.
///
/// P0-фикс №12: вместо хардкода закрывающего маркера «// Доработка END»
/// используются только шаблоны пользователя. Если шаблон содержит {newCode}
/// или {oldCode} — маркер вставляется на место токена, иначе код добавляется
/// сразу после шаблона.
pub fn maintenance_isolation_rules(
    addition_marker: &str,
    modification_marker: &str,
    deletion_marker: &str,
) -> String {
    let mut s = String::from("=== ПРАВИЛА ИЗОЛЯЦИИ ИЗМЕНЕНИЙ (MAINTENANCE) ===\n");
    s.push_str("Ты обязан маркировать свои правки согласно стандартам 1С:\n\n");

    s.push_str(&format!("1. ДОБАВЛЕНИЕ НОВОГО КОДА:\nШаблон маркера:\n{}\n", addition_marker));
    if addition_marker.contains("{newCode}") {
        s.push_str("   Вставь свой новый код ровно на место {newCode}.\n");
    } else {
        s.push_str("   Вставь шаблон, ниже добавь новый код.\n");
    }
    s.push('\n');

    s.push_str(&format!("2. ИЗМЕНЕНИЕ СУЩЕСТВУЮЩЕГО КОДА:\nШаблон маркера:\n{}\n", modification_marker));
    if modification_marker.contains("{newCode}") {
        s.push_str("   Вставь свой исправленный код ровно на место {newCode}.\n");
    } else if modification_marker.contains("{oldCode}") {
        s.push_str("   Вставь исходный код на место {oldCode}, исправленный — сразу после шаблона.\n");
    } else {
        s.push_str("   Вставь шаблон, ниже добавь исправленный код.\n");
    }
    s.push('\n');

    s.push_str(&format!("3. УДАЛЕНИЕ КОДА:\nШаблон маркера:\n{}\n", deletion_marker));
    if deletion_marker.contains("{oldCode}") {
        s.push_str("   Вставь закомментированный старый код на место {oldCode}.\n");
    } else {
        s.push_str("   Вставь шаблон, ниже добавь закомментированный старый код.\n");
    }
    s.push('\n');

    s.push_str("НИКОГДА не удаляй код бесследно. Всегда изолируй изменения или комментируй удаляемое.\n");
    s
}
