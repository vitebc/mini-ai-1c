/// Инструкции по diff-формату правок (Search/Replace).
///
/// P0-фиксы из ревью:
/// - №2: переведено на русский + добавлен готовый пример.
/// - №4: убран EOF_RULE_COMPLETING_CODE.
/// - Исправлено противоречие «2-3 строки контекста» vs «5+ неизменяемых строк»
///   → единое правило «1-2 строки якоря».
/// - Добавлено правило: если <search> не найден — не выдумывать, сообщить.
/// - Добавлено правило удаления кода (пустой replace / закомментировать).
pub const DIFF_FORMAT_INSTRUCTIONS: &str = r#"=== ФОРМАТ ПРАВОК (SEARCH/REPLACE) ===
Все изменения существующего кода оформляй строго XML-блоками:

<diff>
  <search>
[Точный фрагмент оригинала, включая отступы]
  </search>
  <replace>
[Новый фрагмент]
  </replace>
</diff>

ПРАВИЛА:
1. Копируй <search> ДОСЛОВНО из исходника: символ в символ, включая табуляцию и пробелы. НЕ перефразируй и НЕ нормализуй пробелы — иначе блок не найдётся.
2. <search> должен содержать ПОЛНЫЕ строки. Не обрезай строку на середине.
3. Якорь: включи 1-2 строки вокруг правки (для уникальности). Не включай длинные неизменные фрагменты (5+ строк) — это делает поиск хрупким.
4. Для ДОБАВЛЕНИЯ кода: включи строку перед точкой вставки и в <search>, и в <replace>.
5. Для УДАЛЕНИЯ кода: <replace> оставь пустым или закомментируй удаляемое.
6. Изменяй ТОЛЬКО строки, которые просили изменить. Сохраняй логику, имена и комментарии остального кода.
7. Если <search> НЕ найден в файле — НЕ выдумывай. Сообщи об этом пользователю и попроси обновить контекст.
8. Несколько правок — несколькими блоками <diff> подряд, каждый меняет свой участок.
9. Блоки идут сверху вниз и не пересекаются.
10. Если код генерируется с нуля в пустом модуле — используй блок ```bsl, а не <diff>.

ПРИМЕР (отступы — табуляция):

<diff>
  <search>
	Если НЕ ПроверкаДоступа() Тогда
		Возврат Ложь;
	КонецЕсли;
  </search>
  <replace>
	Если НЕ ПроверкаДоступа() Тогда
		ВызватьИсключение "Нет доступа";
	КонецЕсли;
  </replace>
</diff>
"#;
